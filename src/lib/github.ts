import 'server-only';
import {localCmsEnabled} from './access';
import * as remote from './github-remote';
import * as local from './local-cms';
import type {Site} from './schema';
const storage=()=>localCmsEnabled()?local:remote;
export const storageReady=()=>localCmsEnabled()||remote.storageReady();
export const getState=()=>storage().getState();
export const saveDraft=(site:Site,expected:string,email:string,files:Array<{path:string;bytes:Buffer}>=[])=>storage().saveDraft(site,expected,email,files);
export const publishDraft=(expected:string,published:string,email:string)=>storage().publishDraft(expected,published,email);
export const history=()=>storage().history();
export const restoreToDraft=(sha:string,expected:string,email:string)=>storage().restoreToDraft(sha,expected,email);
export const mediaBytes=(name:string)=>storage().mediaBytes(name);
